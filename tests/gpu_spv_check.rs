/// Word index of the `nth` instruction carrying `opcode`, or `None` when absent or malformed.
fn instruction_index(words: &[u32], opcode: u32, nth: usize) -> Option<usize> {
    let mut seen = 0usize;
    let mut index = 5usize;
    while index < words.len() {
        let first = words[index];
        let word_count = usize::try_from(first >> 16).ok()?;
        if word_count == 0 {
            return None;
        }
        if first & 0xffff == opcode {
            if seen == nth {
                return Some(index);
            }
            seen += 1;
        }
        index += word_count;
    }
    None
}

#[test]
fn captured_emitter_module_is_admitted() {
    assert_eq!(check_fragment(&CAPTURED_GEMV_DP4A_MODULE_DYN), Ok(()));
}

#[test]
fn captured_module_carries_the_dot_product_opcode() {
    assert!(instruction_index(&CAPTURED_GEMV_DP4A_MODULE_DYN, 4452, 0).is_some());
}

#[test]
fn zero_word_count_is_refused() {
    let mut words = CAPTURED_GEMV_DP4A_MODULE_DYN;
    words[5] = 17; // `(0 << 16) | OpCapability`: the first instruction frames with zero words.
    assert_eq!(
        check_fragment(&words),
        Err(CheckError::ZeroWordCount { index: 5 })
    );
}

#[test]
fn overrun_word_count_is_refused() {
    let mut words = CAPTURED_GEMV_DP4A_MODULE_DYN;
    words[5] = (65_535 << 16) | 0x0011; // `OpCapability` claiming more words than remain.
    assert_eq!(
        check_fragment(&words),
        Err(CheckError::TruncatedInstruction {
            index: 5,
            word_count: 65_535,
        })
    );
}

#[test]
fn duplicate_result_id_is_refused() {
    let first = instruction_index(&CAPTURED_GEMV_DP4A_MODULE_DYN, 21, 0).expect("first OpTypeInt");
    let second =
        instruction_index(&CAPTURED_GEMV_DP4A_MODULE_DYN, 21, 1).expect("second OpTypeInt");
    let duplicate = CAPTURED_GEMV_DP4A_MODULE_DYN[first + 1];
    let mut words = CAPTURED_GEMV_DP4A_MODULE_DYN;
    words[second + 1] = duplicate; // the second `OpTypeInt` re-defines the first's result id.
    assert_eq!(
        check_fragment(&words),
        Err(CheckError::DuplicateResultId {
            index: second,
            id: duplicate,
        })
    );
}

#[test]
fn out_of_set_opcode_is_refused() {
    let mut words = CAPTURED_GEMV_DP4A_MODULE_DYN;
    words[5] = (words[5] & 0xffff_0000) | 0x00e0; // `OpControlBarrier` (phase 2), same WordCount.
    assert_eq!(
        check_fragment(&words),
        Err(CheckError::OpcodeNotAdmitted {
            index: 5,
            opcode: 224,
        })
    );
}
