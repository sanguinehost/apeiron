#!/usr/bin/env python3
"""Extract and check the real per-entry relocation body in a bounded private build.

The shared `proof/extract/lib.rs` unit does not compile, so this gate never reads it: it writes a
narrow forwarding `#[path]` wrapper that names the real `src/scalar.rs`, `src/cell.rs`,
`src/map/coord.rs` and `src/map/table.rs` (with its textual `include!` of `src/map/table/{state,locator,
prepared}.rs`) and calls the real `Table::relocate_entry` through the regenerating `i64` carrier.
Charon extracts `crate::relocate_entry`; the Aeneas Lean backend writes
`proof/resource/RegenRelocateEntrySource.lean`. `RegenRelocateEntryResource.lean` is then built in
a private package against the pinned patched model at `target/aeneas-model/lean`.

O(B) source/tool/log bytes; external compilation is timed, not assigned constant cost.

  proof/resource/RegenRelocateEntry_gate.py --prepare   regenerate proof/resource/RegenRelocateEntrySource.lean
  proof/resource/RegenRelocateEntry_gate.py --check     check extraction freshness, then build the proof
  proof/resource/RegenRelocateEntry_gate.py --controls   also run the real-source mutation/restore control

The bare invocation runs the same check as `--check`; the flag names the registered command.
"""
from pathlib import Path
import argparse, hashlib, json, os, re, shutil, signal, subprocess, sys, tempfile, time
ROOT = Path(__file__).resolve().parents[2]
TOOLS = ROOT if (ROOT / 'target/aeneas/aeneas').is_file() else Path(os.environ.get('APEIRON_TOOLS') or Path(__file__).resolve().parents[2])
if __name__ == '__main__' and os.environ.get('REGEN_RELOCATE_ENTRY_IN_LANE') != '1':
    deadline = str(time.time() + 535)
    os.execvp('timeout', ['timeout', '--kill-after=5', '540s', 'flock', '-w', '530',
        '/tmp/opencode/apeiron-lane-3.lock', 'systemd-run', '--user', '--scope', '-q', '-p',
        'MemoryMax=12G', '-p', 'MemorySwapMax=0', 'timeout', '--kill-after=5', '525s', 'env',
        'LEAN_NUM_THREADS=1', 'REGEN_RELOCATE_ENTRY_IN_LANE=1',
        'REGEN_RELOCATE_ENTRY_DEADLINE=' + deadline, sys.executable,
        str(Path(__file__).resolve()), *sys.argv[1:]])
START = time.monotonic()
RECORDS = []
OUT = Path('/tmp/opencode/regen-relocate-entry')
OUT.mkdir(parents=True, exist_ok=True)
SCRATCH = Path(tempfile.mkdtemp(prefix='scratch-', dir=tempfile.gettempdir()))
MODULES = ['scalar.rs', 'cell.rs', 'coord.rs', 'table.rs']
MUTATION_NEEDLE = 'reserved.resident.slots[index] = FlatSlot {\n                live: true,'
MUTATION_REPLACEMENT = 'reserved.resident.slots[index] = FlatSlot {\n                live: false,'


def digest(p):
    """O(B) file bytes, O(1) streaming scratch for file size B."""
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()


def run(argv, cwd, label, require=True):
    """Run within the shared whole-invocation deadline; record complete output."""
    left = min(525 - (time.monotonic() - START),
               float(os.environ.get('REGEN_RELOCATE_ENTRY_DEADLINE', time.time() + 525)) - time.time() - 3)
    if left <= 0:
        raise RuntimeError('REGEN_RELOCATE_ENTRY_BUDGET_EXHAUSTED')
    log = OUT / (SCRATCH.name + '-' + label + '.log')
    begin = time.monotonic()
    with log.open('wb') as f:
        p = subprocess.Popen(argv, cwd=cwd, stdout=f, stderr=subprocess.STDOUT,
                             env={**os.environ, 'LEAN_NUM_THREADS': '1'}, start_new_session=True)
        try:
            p.wait(timeout=left)
        except BaseException:
            os.killpg(p.pid, signal.SIGKILL); p.wait(); raise
    text = log.read_text(errors='replace')
    RECORDS.append(dict(label=label, argv=argv, exit=p.returncode,
                        seconds=round(time.monotonic() - begin, 2), log=str(log)))
    if require and p.returncode:
        raise RuntimeError(f'{label}_REJECT {p.returncode}\n{text[-3500:]}')
    return p.returncode, text


def wrapper(table_rs, label):
    """A typed forwarding wrapper: module `#[path]`s at the real sources, one root call."""
    project = SCRATCH / label
    project.mkdir(parents=True, exist_ok=True)
    (project / 'Cargo.toml').write_text(
        '[package]\nname="regen_relocate_entry"\nversion="0.0.0"\nedition="2021"\n'
        '[lib]\npath="lib.rs"\n[workspace]\n')
    lines = ['//! Narrow extraction wrapper: the real relocation body, regenerated carrier.',
             '//! Generated by proof/resource/RegenRelocateEntry_gate.py; no formula is restated.',
             '']
    for name in MODULES:
        path = table_rs if name == 'table.rs' else TOOLS / 'src' / name
        lines.append('#[path = %s]' % json.dumps(str(path)))
        lines.append('pub mod %s;' % name[:-3])
        lines.append('')
    lines += [
        'pub type WordRegenTable =',
        '    table::Table<i64, i64, table::WordHome, 16,',
        '        table::keyrep::Regen<table::keyrep::I64WordCodec>>;',
        '',
        'pub type WordRegenHeld = table::keyrep::Regen<table::keyrep::I64WordCodec>;',
        '',
        '/// The real production per-entry relocation core through the regenerating carrier.',
        'pub fn relocate_entry(',
        '    mut state: WordRegenTable,',
        '    plan: &table::RebuildPlan,',
        '    mut reserved: table::RebuildReserved<WordRegenHeld, i64>,',
        '    entry_at: usize,',
        ') -> (WordRegenTable, table::RebuildReserved<WordRegenHeld, i64>) {',
        '    state.relocate_entry(plan, &mut reserved, entry_at);',
        '    (state, reserved)',
        '}',
        '']
    (project / 'lib.rs').write_text('\n'.join(lines))
    return project


def extract(table_rs, label):
    """Extract the real call closure into RegenRelocateEntrySource.lean."""
    project = wrapper(table_rs, label)
    run(['cargo', 'generate-lockfile', '--offline'], project, label + '-lock')
    run(['cargo', 'check', '--locked', '--offline', '--lib', '--target-dir',
         str(SCRATCH / 'rust-target')], project, label + '-rust-check',
        require=(label != 'mutant'))
    llbc = project / 'regen_relocate_entry.llbc'
    run([str(TOOLS / 'target/aeneas/charon'), 'cargo', '--sysroot', 'default', '--preset',
         'aeneas', '--dest-file', str(llbc), '--start-from', 'crate::relocate_entry', '--',
         '--manifest-path', str(project / 'Cargo.toml'), '--locked', '--offline', '--lib',
         '--target-dir', str(SCRATCH / 'charon-target')], project, label + '-charon')
    run([str(TOOLS / 'target/aeneas/aeneas'), '-backend', 'lean', '-dest', str(project),
         '-warnings-as-errors', '-no-progress-bar', '-all-computable', str(llbc)], project,
        label + '-aeneas')
    raw = project / 'RegenRelocateEntry.lean'
    generated = project / 'RegenRelocateEntrySource.lean'
    text = raw.read_text()
    # Aeneas may leave blanks at line ends; normalize, as proof/regen.sh does.
    text = '\n'.join(line.rstrip() for line in text.split('\n'))
    raw.write_text(text)
    # The model patch supplies the Option externals; drop their stubs as regen.sh does.
    run([sys.executable, str(TOOLS / 'proof/strip-modeled-axioms.py'), str(raw)],
        ROOT, label + '-strip')
    text = raw.read_text()
    text = text.replace(str(TOOLS) + '/src/', 'src/').replace(str(TOOLS) + '/', '')
    if re.search(r'\b(axiom|sorry|admit)\b', text):
        raise RuntimeError('REGEN_RELOCATE_ENTRY_UNMODELED_SOURCE')
    generated.write_text(text)
    return generated, text


def prepare_lean():
    """Private local package; dependency artifacts read from the pinned compatible lane."""
    p = SCRATCH / 'lean'; p.mkdir(parents=True)
    (p / 'lean-toolchain').write_bytes((TOOLS / 'proof/dispatch/lean-toolchain').read_bytes())
    (p / 'lakefile.lean').write_text(
        'import Lake\nopen Lake DSL\npackage regenRelocateEntryProof where\n'
        '  leanOptions := #[⟨`autoImplicit,false⟩,⟨`warningAsError,true⟩]\n'
        'require aeneas from ' + json.dumps(str(TOOLS / 'target/aeneas-model/lean')) + '\n'
        '@[default_target] lean_lib RegenRelocateEntry where\n'
        '  roots := #[`RegenRelocateEntrySource,`RegenRelocateEntryResource]\n')
    manifest = json.loads((TOOLS / 'proof/dispatch/lake-manifest.json').read_text())
    manifest['name'] = 'regenRelocateEntryProof'
    for dep in manifest['packages']:
        if dep['name'] == 'aeneas':
            dep['dir'] = str(TOOLS / 'target/aeneas-model/lean')
    (p / 'lake-manifest.json').write_text(json.dumps(manifest))
    deps = p / '.lake/packages'; deps.mkdir(parents=True)
    for dep in (TOOLS / 'proof/dispatch/.lake/packages').iterdir():
        (deps / dep.name).symlink_to(dep.resolve(), target_is_directory=True)
    return p


def build_proof(p, source_text, label):
    """Build the resource file against one extraction; return the exit status and output."""
    (p / 'RegenRelocateEntrySource.lean').write_text(source_text)
    shutil.copyfile(ROOT / 'proof/resource/RegenRelocateEntryResource.lean',
                    p / 'RegenRelocateEntryResource.lean')
    return run(['lake', 'build', 'RegenRelocateEntryResource'], p, label)


def main():
    a = argparse.ArgumentParser()
    a.add_argument('--prepare', action='store_true')
    a.add_argument('--check', action='store_true')
    a.add_argument('--controls', action='store_true')
    args = a.parse_args()
    run(['rustc', '--version'], ROOT, 'rustc-version')
    run(['cargo', '--version'], ROOT, 'cargo-version')
    run(['lean', '--version'], ROOT, 'lean-version')
    generated, fresh = extract(TOOLS / 'src/map/table.rs', 'fresh')
    dest = ROOT / 'proof/resource/RegenRelocateEntrySource.lean'
    if args.prepare:
        shutil.copyfile(generated, dest); print('REGEN_RELOCATE_ENTRY_EXTRACTION_READY'); return
    if fresh != dest.read_text():
        raise RuntimeError('REGEN_RELOCATE_ENTRY_EXTRACTION_DRIFT')
    proof = ROOT / 'proof/resource/RegenRelocateEntryResource.lean'
    if re.search(r'\b(sorry|admit|axiom)\b|set_option maxHeartbeats 0', proof.read_text()):
        raise RuntimeError('REGEN_RELOCATE_ENTRY_PROOF_POLICY_REJECT')
    p = prepare_lean()
    code, text = build_proof(p, fresh, 'fresh-proof')
    if 'REGEN_RELOCATE_ENTRY_KERNEL_OK' not in text:
        raise RuntimeError('REGEN_RELOCATE_ENTRY_AUDIT_MISSING')
    if args.controls:
        original = (TOOLS / 'src/map/table.rs').read_text()
        if original.count(MUTATION_NEEDLE) != 1:
            raise RuntimeError('REGEN_RELOCATE_ENTRY_CONTROL_TARGET_MISSING')
        mutant_dir = SCRATCH / 'mutant/src'
        (mutant_dir / 'table').mkdir(parents=True, exist_ok=True)
        (mutant_dir / 'table.rs').write_text(original.replace(MUTATION_NEEDLE, MUTATION_REPLACEMENT))
        for child in (TOOLS / 'src/table').iterdir():
            if child.is_file():
                shutil.copyfile(child, mutant_dir / 'table' / child.name)
        _, mutant = extract(mutant_dir / 'table.rs', 'mutant')
        (p / 'RegenRelocateEntrySource.lean').write_text(mutant)
        code, text = run(['lake', 'build', 'RegenRelocateEntryResource'], p, 'mutant-proof',
                         require=False)
        if (code == 0 or 'RegenRelocateEntryResource.lean:' not in text
                or not any(x in text for x in ['unsolved goals', 'type mismatch', 'Tactic',
                                               'motive is not type correct',
                                               'forbidden axioms'])):
            raise RuntimeError('REGEN_RELOCATE_ENTRY_CONTROL_NOT_ATTRIBUTABLE\n' + text[-1800:])
        print('REGEN_RELOCATE_ENTRY_REAL_SOURCE_CONTROL_RED')
        _, restored = extract(TOOLS / 'src/map/table.rs', 'restored')
        # Source-location comments differ for disposable absolute source paths; compare the rest.
        strip = lambda s: re.sub(r'/\*.*?\*/|/--.*?-/', '', s, flags=re.S)
        if strip(restored) != strip(dest.read_text()):
            raise RuntimeError('REGEN_RELOCATE_ENTRY_RESTORE_BODY_DRIFT')
        (p / 'RegenRelocateEntrySource.lean').write_text(restored)
        run(['lake', 'build', 'RegenRelocateEntryResource'], p, 'restored-proof')
        print('REGEN_RELOCATE_ENTRY_REAL_SOURCE_CONTROL_RESTORED')
    print('REGEN_RELOCATE_ENTRY_SOURCE_RESOURCE_OK')


if __name__ == '__main__':
    status = 1
    try:
        main(); status = 0
    finally:
        paths = [TOOLS / 'target/aeneas/charon', TOOLS / 'target/aeneas/aeneas',
                 TOOLS / 'target/aeneas-model/lean/lean-toolchain',
                 TOOLS / 'proof/dispatch/lean-toolchain', TOOLS / 'proof/dispatch/lake-manifest.json',
                 TOOLS / 'src/map/table.rs', ROOT / 'proof/resource/RegenRelocateEntry_gate.py',
                 ROOT / 'proof/resource/RegenRelocateEntrySource.lean',
                 ROOT / 'proof/resource/RegenRelocateEntryResource.lean']
        (OUT / (SCRATCH.name + '-receipt.json')).write_text(json.dumps(
            dict(exit=status, seconds=round(time.monotonic() - START, 2), budget=540,
                 argv=[sys.executable, *sys.argv], lane='/tmp/opencode/apeiron-lane-3.lock',
                 memory_max='12G', swap_max=0, threads=1,
                 deadline=os.environ.get('REGEN_RELOCATE_ENTRY_DEADLINE'), records=RECORDS,
                 sha256={str(x): digest(x) for x in paths if x.is_file()},
                 mutation=dict(needle=MUTATION_NEEDLE, replacement=MUTATION_REPLACEMENT,
                               file='src/map/table.rs'),
                 trust='Aeneas/Charon, the Lean kernel and linter, cargo/rustc, IO/process and '
                       'dependency artifacts; the resource claim excludes GPU/hardware timing, the '
                       'unextracted relocate_all traversal, and the prepared-resource adapter'),
            indent=2) + '\n')
        shutil.rmtree(SCRATCH, ignore_errors=True)