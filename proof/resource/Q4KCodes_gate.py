#!/usr/bin/env python3
"""Extract and check the real Q4_K code unpack in a bounded private build.

O(B) source/tool/log bytes; external compilation is timed, not assigned constant cost.
The temporary manifest/wrapper calls the production `#[path]` body; no substitute algorithm.
The shared `proof/extract/lib.rs` unit is never used: it does not currently compile, so the
narrow forwarding wrapper below is the only extraction root.
"""
from pathlib import Path
import argparse, hashlib, json, os, re, shutil, signal, subprocess, sys, tempfile, time
ROOT = Path(__file__).resolve().parents[2]
TOOLS = ROOT if (ROOT/'target/aeneas/aeneas').is_file() else Path('/home/socol/Workspace/apeiron')
REL = 'src/format/quant.rs'
if __name__ == '__main__' and os.environ.get('Q4KCODES_IN_LANE') != '1':
    deadline = str(time.time()+535)
    os.execvp('timeout', ['timeout','--kill-after=5','540s','flock','-w','530','/tmp/opencode/apeiron-lane-1.lock',
        'systemd-run','--user','--scope','-q','-p','MemoryMax=12G','-p','MemorySwapMax=0',
        'timeout','--kill-after=5','525s','env','LEAN_NUM_THREADS=1','Q4KCODES_IN_LANE=1',
        'Q4KCODES_DEADLINE='+deadline,sys.executable,str(Path(__file__).resolve()),*sys.argv[1:]])
START = time.monotonic()
RECORDS = []
OUT = Path('/tmp/opencode/q4kcodes-resource')
OUT.mkdir(parents=True, exist_ok=True)
# Heavy build trees live off the tmpfs: the record of the tmpfs-exhaustion lane failure.
SCRATCH = Path(tempfile.mkdtemp(prefix='source-', dir=Path(os.environ.get('Q4KCODES_SCRATCH_ROOT','/home/socol/oc-tmp'))))

def digest(p):
    """O(B) file bytes, O(1) streaming scratch for file size B."""
    with p.open('rb') as f:
        return hashlib.file_digest(f, 'sha256').hexdigest()

def run(argv, cwd, label, require=True):
    """Run within the shared whole-invocation deadline; record complete output."""
    left = min(525 - (time.monotonic()-START), float(os.environ.get('Q4KCODES_DEADLINE', time.time()+525))-time.time()-3)
    if left <= 0:
        raise RuntimeError('Q4K_CODES_BUDGET_EXHAUSTED')
    log = OUT / (SCRATCH.name+'-'+label+'.log')
    begin = time.monotonic()
    with log.open('wb') as f:
        p = subprocess.Popen(argv, cwd=cwd, stdout=f, stderr=subprocess.STDOUT,
                             env={**os.environ,'LEAN_NUM_THREADS':'1'}, start_new_session=True)
        try:
            p.wait(timeout=left)
        except BaseException:
            os.killpg(p.pid, signal.SIGKILL); p.wait(); raise
    text = log.read_text(errors='replace')
    RECORDS.append(dict(label=label,argv=argv,exit=p.returncode,seconds=time.monotonic()-begin,log=str(log)))
    if require and p.returncode:
        raise RuntimeError(f'{label}_REJECT {p.returncode}\n{text[-3500:]}')
    return p.returncode,text

def extract(source, label):
    """Create only a typed forwarding wrapper and extract its real call closure."""
    project = SCRATCH/label
    project.mkdir()
    (project/'Cargo.toml').write_text('[package]\nname="q4k_codes_source"\nversion="0.0.0"\nedition="2021"\n[lib]\npath="lib.rs"\n[workspace]\n')
    (project/'lib.rs').write_text(
        '#[path = '+json.dumps(str(source))+']\npub mod quant;\n'
        '/// Typed forwarding wrapper over the real `format::quant::q4_k_codes` body.\n'
        'pub fn word_q4_k_codes(blk: &[u8]) -> Result<[u8; quant::QK_K], quant::QuantError> {\n'
        '    quant::q4_k_codes(blk)\n}\n')
    run(['cargo','generate-lockfile','--offline'], project, label+'-lock')
    run(['cargo','test','--locked','--offline','--lib','--target-dir',str(SCRATCH/'rust-target')], project, label+'-rust-tests', require=(label != 'mutant'))
    llbc = project/'q4k_codes_source.llbc'
    run([str(TOOLS/'target/aeneas/charon'),'cargo','--sysroot','default','--preset','aeneas','--dest-file',str(llbc),
         '--start-from','crate::word_q4_k_codes','--','--manifest-path',str(project/'Cargo.toml'),'--locked','--offline','--lib',
         '--target-dir',str(SCRATCH/'charon-target')], project, label+'-charon')
    run([str(TOOLS/'target/aeneas/aeneas'),'-backend','lean','-dest',str(project),'-warnings-as-errors',
         '-no-progress-bar','-all-computable',str(llbc)], project, label+'-aeneas')
    generated = None
    for candidate in sorted(project.glob('*.lean')):
        if 'AUTOMATICALLY GENERATED BY AENEAS' in candidate.read_text():
            generated = candidate
    if generated is None:
        raise RuntimeError('Q4K_CODES_NO_GENERATED_SOURCE')
    text = generated.read_text().replace(str(source), REL)
    if re.search(r'\b(axiom|sorry|admit)\b', text):
        raise RuntimeError('Q4K_CODES_UNMODELED_SOURCE')
    normalized = project/'Q4KCodesSource.lean'
    normalized.write_text(text)
    return normalized

def prepare_lean():
    """Private local package; dependency artifacts read from the pinned compatible lane."""
    p = SCRATCH/'lean'; p.mkdir()
    (p/'lean-toolchain').write_bytes((TOOLS/'proof/dispatch/lean-toolchain').read_bytes())
    (p/'lakefile.lean').write_text('import Lake\nopen Lake DSL\npackage q4kCodesProof where\n  leanOptions := #[⟨`autoImplicit,false⟩,⟨`warningAsError,true⟩]\nrequire aeneas from '+json.dumps(str(TOOLS/'target/aeneas-model/lean'))+'\n@[default_target] lean_lib Q4KCodes where\n  roots := #[`Q4KCodesSource,`Q4KCodesResource]\n')
    manifest = json.loads((TOOLS/'proof/dispatch/lake-manifest.json').read_text()); manifest['name'] = 'q4kCodesProof'
    for dep in manifest['packages']:
        if dep['name'] == 'aeneas': dep['dir'] = str(TOOLS/'target/aeneas-model/lean')
    (p/'lake-manifest.json').write_text(json.dumps(manifest))
    deps = p/'.lake/packages'; deps.mkdir(parents=True)
    for dep in (TOOLS/'proof/dispatch/.lake/packages').iterdir(): (deps/dep.name).symlink_to(dep.resolve(), target_is_directory=True)
    return p

def main():
    args = argparse.ArgumentParser()
    args.add_argument('--prepare', action='store_true')
    args.add_argument('--check', action='store_true')
    args.add_argument('--controls', action='store_true')
    a = args.parse_args()
    source = ROOT/REL
    run(['rustc','--version'], ROOT, 'rustc-version')
    run(['cargo','--version'], ROOT, 'cargo-version')
    run(['lean','--version'], ROOT, 'lean-version')
    generated = extract(source, 'fresh')
    dest = ROOT/'proof/resource/Q4KCodesSource.lean'
    if a.prepare:
        shutil.copyfile(generated, dest); print('Q4K_CODES_EXTRACTION_READY'); return
    if generated.read_bytes() != dest.read_bytes():
        raise RuntimeError('Q4K_CODES_EXTRACTION_DRIFT')
    proof = ROOT/'proof/resource/Q4KCodesResource.lean'
    if re.search(r'\b(sorry|admit|axiom)\b|set_option maxHeartbeats 0', proof.read_text()):
        raise RuntimeError('Q4K_CODES_PROOF_POLICY_REJECT')
    p = prepare_lean()
    shutil.copyfile(dest, p/'Q4KCodesSource.lean'); shutil.copyfile(proof, p/'Q4KCodesResource.lean')
    code, text = run(['lake','build','Q4KCodesResource'], p, 'fresh-proof')
    if 'Q4K_CODES_KERNEL_OK' not in text: raise RuntimeError('Q4K_CODES_AUDIT_MISSING')
    if a.controls:
        original = source.read_text()
        # Real inner-loop body of `q4_k_codes`: the loop-rank advance. `l += 2` keeps the
        # termination guard and the two writes but halves the iterations and skips positions.
        needle = ('            out[64 * b + l] = qs[32 * b + l] & 0xF;\n'
                  '            out[64 * b + 32 + l] = qs[32 * b + l] >> 4;\n'
                  '            l += 1;\n')
        if original.count(needle) != 1: raise RuntimeError('Q4K_CODES_CONTROL_TARGET_MISSING')
        mutant = SCRATCH/'quant.rs'; mutant.write_text(original.replace(needle, needle.replace('l += 1;', 'l += 2;')))
        freshmut = extract(mutant, 'mutant'); shutil.copyfile(freshmut, p/'Q4KCodesSource.lean')
        code, text = run(['lake','build','Q4KCodesResource'], p, 'mutant-proof', require=False)
        if code != 1 or 'Q4KCodesResource.lean:' not in text or not any(x in text for x in ['unsolved goals','type mismatch','Tactic','failed to prove']):
            raise RuntimeError('Q4K_CODES_CONTROL_NOT_ATTRIBUTABLE '+text[-1800:])
        print('Q4K_CODES_REAL_SOURCE_CONTROL_RED')
        mutant.write_text(original); restored = extract(mutant, 'restored')
        # Source-location comments differ for disposable absolute source paths; compare executable text.
        strip = lambda s: re.sub(r'/\*.*?\*/|/--.*?-/', '', s, flags=re.S)
        if strip(restored.read_text()) != strip(dest.read_text()): raise RuntimeError('Q4K_CODES_RESTORE_BODY_DRIFT')
        shutil.copyfile(dest, p/'Q4KCodesSource.lean'); run(['lake','build','Q4KCodesResource'], p, 'restored-proof')
        print('Q4K_CODES_REAL_SOURCE_CONTROL_RESTORED')
    print('Q4K_CODES_SOURCE_RESOURCE_OK')

if __name__ == '__main__':
    status = 1
    try:
        main(); status = 0
    finally:
        source_paths = [TOOLS/'target/aeneas/charon-driver', TOOLS/'target/aeneas-model/lean/lean-toolchain', TOOLS/'proof/dispatch/lean-toolchain', ROOT/REL, ROOT/'proof/resource/Q4KCodes_gate.py', ROOT/'proof/resource/Q4KCodesSource.lean', ROOT/'proof/resource/Q4KCodesResource.lean', TOOLS/'target/aeneas/charon', TOOLS/'target/aeneas/aeneas', TOOLS/'proof/dispatch/lake-manifest.json']
        (OUT/(SCRATCH.name+'-receipt.json')).write_text(json.dumps(dict(exit=status,seconds=time.monotonic()-START,budget=540,argv=[sys.executable,*sys.argv],lane='/tmp/opencode/apeiron-lane-1.lock',memory_max='12G',swap_max=0,threads=1,deadline=os.environ.get('Q4KCODES_DEADLINE'),records=RECORDS,sha256={str(p):digest(p) for p in source_paths if p.is_file()},trust='Aeneas/Charon, compiler, IO/process/dependencies; scalar source/resource claim excludes GPU/hardware timing'),indent=2)+'\n')
        shutil.rmtree(SCRATCH, ignore_errors=True)
