#!/usr/bin/env python3
"""Fresh source refinement gate. IO and Lean invocation are trusted checker code."""
from pathlib import Path
import argparse
import hashlib
import json
import os
import re
import shutil
import signal
import subprocess
import tempfile
import time

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ('tools/dispatch/core.rs', 'proof/dispatch/extract/Cargo.toml',
           'proof/dispatch/extract/Cargo.lock', 'proof/dispatch/extract/lib.rs',
           'proof/dispatch/lakefile.lean', 'proof/dispatch/lean-toolchain',
           'proof/dispatch/lake-manifest.json', 'proof/dispatch/Dispatch/Extracted.lean',
           'proof/dispatch/Dispatch/Spec.lean', 'proof/dispatch/Dispatch/Refinement.lean',
           'proof/dispatch/Dispatch/Audit.lean', 'proof/dispatch/regen.sh', 'proof/dispatch/gate.py')
START = time.monotonic()
PARENT_DEADLINE = os.environ.get("APEIRON_DISPATCH_DEADLINE_EPOCH")
RECORDS = []
BASE = Path('/home/socol/oc-tmp/rust-admission')
BASE.mkdir(parents=True, exist_ok=True)
SCRATCH = Path(tempfile.mkdtemp(prefix='proof-', dir=BASE))
LOGS = Path('/tmp/opencode/rust-admission')
LOGS.mkdir(parents=True, exist_ok=True)


def run(argv, cwd, label):
    """O(L) recorded log bytes; external work shares the 525s remaining deadline."""
    left = 525 - (time.monotonic() - START)
    if PARENT_DEADLINE is not None:
        left = min(left, int(PARENT_DEADLINE) - time.time() - 3)
    if left <= 0:
        raise RuntimeError('DISPATCH_PROOF_BUDGET_EXHAUSTED')
    log = LOGS / (SCRATCH.name + '-' + label + '.log')
    begin = time.monotonic()
    with log.open('wb') as f:
        proc = subprocess.Popen(argv, cwd=cwd, stdout=f, stderr=subprocess.STDOUT,
                                start_new_session=True, env={**os.environ, 'LEAN_NUM_THREADS': '1'})
        try:
            proc.wait(timeout=left)
        except BaseException:
            os.killpg(proc.pid, signal.SIGKILL)
            proc.wait()
            raise
    output = log.read_text(errors='replace')
    RECORDS.append(dict(label=label, argv=argv, cwd=str(cwd), exit=proc.returncode,
                        seconds=time.monotonic()-begin, log=str(log)))
    return proc.returncode, output


def extract(root, label):
    """O(B) generated bytes plus bounded compiler work; no constant-time claim."""
    out = SCRATCH / label
    out.mkdir()
    llbc = out / 'dispatch_extract.llbc'
    cmd = [str(ROOT/'target/aeneas/charon'), 'cargo', '--sysroot', 'default',
           '--preset', 'aeneas', '--dest-file', str(llbc)]
    for name in ['same', 'start', 'advance', 'finish', 'complete', 'witness_success', 'witness_refusal']:
        cmd += ['--start-from', 'crate::'+name]
    cmd += ['--', '--manifest-path', 'proof/dispatch/extract/Cargo.toml', '--locked',
            '--offline', '--lib', '--target-dir', str(SCRATCH/'extract-target')]
    code, output = run(cmd, root, label+'-charon')
    if code:
        raise RuntimeError('DISPATCH_EXTRACTION_REJECT '+output[-1800:])
    code, output = run([str(ROOT/'target/aeneas/aeneas'), '-backend', 'lean', '-dest', str(out),
                        '-warnings-as-errors', '-no-progress-bar', '-all-computable', str(llbc)],
                       root, label+'-aeneas')
    if code:
        raise RuntimeError('DISPATCH_TRANSLATION_REJECT '+output[-1800:])
    generated = out/'DispatchExtract.lean'
    if re.search(r'\b(axiom|sorry|admit)\b', generated.read_text()):
        raise RuntimeError('DISPATCH_UNMODELED_EXTRACTION')
    return generated


def controls():
    """O(B) copied harness bytes; only this disposable source copy is mutated."""
    root = SCRATCH/'control'
    for rel in SOURCES:
        dest = root/rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(ROOT/rel, dest)
    (root/'target').mkdir()
    (root/'target/aeneas-model').symlink_to((ROOT/'target/aeneas-model').resolve(), target_is_directory=True)
    packages = root/'proof/dispatch/.lake/packages'
    packages.mkdir(parents=True)
    for dep in (ROOT/'proof/dispatch/.lake/packages').iterdir():
        (packages/dep.name).symlink_to(dep.resolve(), target_is_directory=True)
    source = root/'tools/dispatch/core.rs'
    original = source.read_text()
    needle = 'if obs.exit != 0 || !session.identity.same(obs.identity)'
    if original.count(needle) != 1:
        raise RuntimeError('DISPATCH_CONTROL_TARGET_MISSING')
    source.write_text(original.replace(needle,
        'if (match obs.stage { Stage::Certificate => false, _ => obs.exit != 0 }) || !session.identity.same(obs.identity)'))
    shutil.copyfile(extract(root, 'mutant'), root/'proof/dispatch/Dispatch/Extracted.lean')
    code, output = run(['lake', 'build', 'Dispatch.Audit'], root/'proof/dispatch', 'mutant-proof')
    if code != 1 or 'Dispatch/Refinement.lean:27:' not in output or 'unsolved goals' not in output:
        raise RuntimeError('DISPATCH_CONTROL_NOT_ATTRIBUTABLE '+output[-1800:])
    source.write_text(original)
    generated = extract(root, 'restored')
    if generated.read_bytes() != (ROOT/'proof/dispatch/Dispatch/Extracted.lean').read_bytes():
        raise RuntimeError('DISPATCH_CONTROL_RESTORE_DRIFT')
    shutil.copyfile(generated, root/'proof/dispatch/Dispatch/Extracted.lean')
    code, output = run(['lake', 'build', 'Dispatch.Audit'], root/'proof/dispatch', 'restored-proof')
    if code or 'DISPATCH_KERNEL_OK Dispatch.Refinement.permit_iff' not in output:
        raise RuntimeError('DISPATCH_CONTROL_RESTORE_REJECT '+output[-1800:])
    print('DISPATCH_SOURCE_CONTROL_OK')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--controls', action='store_true')
    args = parser.parse_args()
    if (ROOT/'proof/dispatch/lean-toolchain').read_text().strip() != 'leanprover/lean4:v4.31.0':
        raise RuntimeError('DISPATCH_TOOLCHAIN_REJECT')
    generated = extract(ROOT, 'fresh')
    destination = ROOT/'proof/dispatch/Dispatch/Extracted.lean'
    if args.check:
        if generated.read_bytes() != destination.read_bytes():
            raise RuntimeError('DISPATCH_STALE_EXTRACTION')
    else:
        shutil.copyfile(generated, destination)
    code, output = run(['lake', 'build', 'Dispatch.Audit'], ROOT/'proof/dispatch', 'proof')
    if code or 'DISPATCH_KERNEL_OK Dispatch.Refinement.permit_iff' not in output:
        raise RuntimeError('DISPATCH_REFINEMENT_REJECT '+output[-1800:])
    if args.controls:
        controls()
    print('DISPATCH_SOURCE_REFINEMENT_OK')


if __name__ == '__main__':
    try:
        main()
    finally:
        # O(B) source/tool bytes hashed once; identities bind this receipt, not HEAD alone.
        files = {str(ROOT/rel): hashlib.sha256((ROOT/rel).read_bytes()).hexdigest() for rel in SOURCES if (ROOT/rel).is_file()}
        for name in ['charon', 'charon-driver', 'aeneas']:
            path = ROOT/'target/aeneas'/name
            if path.is_file():
                files[str(path.resolve())] = hashlib.file_digest(path.open('rb'), 'sha256').hexdigest()
        receipt = dict(seconds=time.monotonic()-START, files=files, records=RECORDS,
                       trust='IO/process/toolchain, Charon/Aeneas semantics, rustc/LLVM and OS remain outside the Lean theorem.')
        (LOGS/(SCRATCH.name+'-receipt.json')).write_text(json.dumps(receipt, indent=2)+'\n')
        shutil.rmtree(SCRATCH)
