"""Deterministic table declaration shards and complete-family freshness.

An external output uses its parent as the Lean import search root: Foo.lean
imports Foo.Chunk01 from Foo/Chunk01.lean. Callers compiling it must include
that parent in LEAN_PATH. Prefix zero retains arbitrary legacy output paths.
"""

from __future__ import annotations

from pathlib import Path
import re

PREFIX_COUNT = 11
BODY_LINES = 1400
FILE_LINES = 1500
MAX_SHARDS = 12
NAMESPACE = "Iota.Generated.Table"


def declaration_layout(monolith: str) -> tuple[str, list[str], str]:
    """Split the renderer's fixed layout in O(text bytes) time and space.

    Blank lines delimit complete leaf/theorem or append/theorem blocks; the
    source renderer emits byte values, so source text cannot inject delimiters.
    """
    start = monolith.index("def tablePath : String :=")
    end = monolith.index("def closurePaths : List String :=", start)
    body = monolith[start:end]
    if not body.endswith("\n\n"):
        raise ValueError("table declaration body lacks its final separator")
    blocks = [block + "\n\n" for block in body[:-2].split("\n\n")]
    return monolith[:start], blocks, monolith[end:]


def pack_blocks(blocks: list[str]) -> list[list[str]]:
    """Pack complete blocks in O(total text bytes) time and O(blocks) space.

    Each block is counted once; its trailing blank separator counts toward
    the body cap, and an indivisible oversized block is rejected.
    """
    groups: list[list[str]] = []
    current: list[str] = []
    used = 0
    for block in blocks:
        cost = len(block.splitlines())
        if cost > BODY_LINES:
            raise ValueError("indivisible table declaration exceeds body line cap")
        if current and used + cost > BODY_LINES:
            groups.append(current)
            current = []
            used = 0
        current.append(block)
        used += cost
    if current:
        groups.append(current)
    if len(groups) > MAX_SHARDS:
        raise ValueError("table declaration layout exceeds shard count cap")
    return groups


def module_prefix(output: Path, corpus_root: Path) -> str:
    """Resolve internal/external module paths in O(path bytes) time and space."""
    if output.suffix != ".lean":
        raise ValueError("sharded table output must have a .lean suffix")
    try:
        relative = output.relative_to(corpus_root.resolve())
    except ValueError:
        relative = Path(output.name)
    components = relative.with_suffix("").parts
    if not all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", item) for item in components):
        raise ValueError("table output contains an invalid Lean module identifier")
    return ".".join(components)


def render_table_outputs(monolith: str, output: Path, helper: tuple[str, ...],
                         corpus_root: Path) -> dict[Path, str]:
    """Render the installed prefix and remaining root in O(text bytes) space/time.

    Blocks are traversed a bounded number of times; no declaration is split.
    The root retains a large suffix during migration. The final root and every
    emitted shard must fit the full-file cap; prefix zero is the legacy bytes.
    """
    output = output.resolve()
    header, blocks, footer = declaration_layout(monolith)
    groups = pack_blocks(blocks)
    if not 0 <= PREFIX_COUNT <= len(groups):
        raise ValueError("table shard prefix is outside the declaration layout")
    if PREFIX_COUNT == 0:
        return {output: monolith}
    prefix = module_prefix(output, corpus_root)
    family = output.with_suffix("")
    outputs: dict[Path, str] = {}
    previous = "Iota.Generated.TableSupport"
    for index, group in enumerate(groups[:PREFIX_COUNT], 1):
        module = f"{prefix}.Chunk{index:02d}"
        imports = ["Iota.Generated.TableSupport"]
        if index > 1:
            imports.append(previous)
        text = "\n".join([
            "-- Generated by tools/iota/export.py; do not edit.",
            *[f"import {name}" for name in imports],
            f"namespace {NAMESPACE}", "", *helper,
        ]) + "\n" + "".join(group) + f"end {NAMESPACE}\n"
        if len(text.splitlines()) > FILE_LINES:
            raise ValueError("rendered table shard exceeds full-file line cap")
        outputs[family / f"Chunk{index:02d}.lean"] = text
        previous = module
    header = header.replace(f"namespace {NAMESPACE}\n",
                            f"import {previous}\nnamespace {NAMESPACE}\n", 1)
    root = header + "".join(block for group in groups[PREFIX_COUNT:] for block in group) + footer
    if PREFIX_COUNT == len(groups) and len(root.splitlines()) > FILE_LINES:
        raise ValueError("final table root exceeds full-file line cap")
    outputs[output] = root
    return outputs


def reject_stale_shards(outputs: dict[Path, str], output: Path) -> None:
    """Check family membership in O(existing files + expected paths) space/time.

    Every Lean file below the family directory belongs to this output; an
    unexpected file rejects both freshness and generation, without deletion.
    """
    family = output.resolve().with_suffix("")
    expected = {path for path in outputs if path.is_relative_to(family)}
    actual = set(family.rglob("*.lean")) if family.is_dir() else set()
    unexpected = actual - expected
    if unexpected:
        raise ValueError("unexpected table shard: " + str(sorted(unexpected)[0]))


def check_output_map(outputs: dict[Path, str], output: Path) -> None:
    """Compare every expected file in O(total expected/actual bytes) time.

    Text is loaded one file at a time in addition to the rendered output map.
    """
    reject_stale_shards(outputs, output)
    for path, text in outputs.items():
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            raise ValueError(f"generated source binding differs: {path}")
