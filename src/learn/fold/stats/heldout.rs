/// A refused held-out evaluation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HeldOutError {
    /// A whole-model [`forward`] refused: an empty sequence, a token past the vocabulary, a shape
    /// disagreement or an overflow.
    Model(ModelError),
    /// A head row refused: a shape or overflow, or the unreachable `exp`/`ln` refusals.
    Head(HeadError),
    /// The evaluator's own shape check: an empty sequence list, a sequence shorter than two tokens,
    /// a zero vocabulary, a logits buffer that is not `t × vocab`, or token metadata that does not
    /// cover the scored rows.
    Shape(String),
    /// A checked `i128` accumulation left its range, or a grid word left `i64`.
    Overflow,
    /// The engine source refused — a decode state, a prefill or a head row — or two engines disagree
    /// on geometry; the carried text is that error's own message, prefixed by the phase.
    Engine(String),
}

/// The per-chunk score against a stored base: llama.cpp's `--kl-divergence` protocol.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BaseScore {
    /// Scored positions, `n_ctx − 1 − n_ctx/2`.
    pub tokens: u64,
    /// Mean forward `KL(p_base ‖ p_student)` per position, in nats, as a `Q32.32` word
    /// (`ONE = 2^32`), over base entries with `log p > −16` exactly as the reference sums it.
    pub kl: i64,
    /// Fraction of scored positions whose student `argmax` equals the base row's `argmax`, as a
    /// `Q32.32` word (`ONE` is agreement on every position).
    pub top1: i64,
    /// Mean `−log p_student(next token)` over the scored positions, in nats, as a `Q32.32` word.
    pub nll_student: i64,
    /// Mean `−log p_base(next token)` over the scored positions, in nats, as a `Q32.32` word:
    /// `log` of llama.cpp's base PPL column.
    pub nll_base: i64,
}

/// The scored held-out quality of a student against a teacher.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HeldOut {
    /// Scored positions `Σ_i T_i`: the denominator of `kl`, `tv` and `top1`.
    pub tokens: u64,
    /// Mean forward `KL(teacher ‖ student)` per position, in nats, as a `Q32.32` word.
    pub kl: i64,
    /// Mean total variation `½Σ_x |p_teacher(x) − p_student(x)|` per position, in `[0, ONE]`, as a
    /// `Q32.32` word.
    pub tv: i64,
    /// Fraction of positions where the teacher and student `argmax` agree, in `[0, ONE]`, as a
    /// `Q32.32` word.
    pub top1: i64,
    /// Mean `−log p_student(next token)` in nats over the next-token positions (`T_i − 1` each),
    /// as a `Q32.32` word.
    pub nll_student: i64,
    /// Mean `−log p_teacher(next token)` in nats, over the same positions as `nll_student`, as a
    /// `Q32.32` word.
    pub nll_teacher: i64,
}

/// A shifted logit below `−16·ONE` has `p = 0`: the rule [`crate::learn::grad::head`] applies.
const FLUSH: i128 = -16 * (1_i128 << 32);

/// Exact Q32.32 accumulators over the scored positions; the division into the mean words happens
/// once, in [`Acc::finish`].
#[derive(Debug, Clone, Copy, Default)]
struct Acc {
    tokens: u64,
    pairs: u64,
    kl: i128,
    tv: i128,
    top1: u64,
    nll_t: i128,
    nll_s: i128,
}

/// First index of the row maximum, ties to the lower index; `None` for an empty row.
///
/// # Complexity
/// `O(v)` comparisons; space `O(1)`.
fn argmax(row: &[i64]) -> Option<usize> {
    let mut best: Option<(usize, i64)> = None;
    for (i, &z) in row.iter().enumerate() {
        if best.is_none_or(|(_, b)| b < z) {
            best = Some((i, z));
        }
    }
    best.map(|(i, _)| i)
}

/// Checked `i128` addition.
fn add(a: i128, b: i128) -> Result<i128, HeldOutError> {
    a.checked_add(b).ok_or(HeldOutError::Overflow)
}

/// `n / d` rounded to nearest, ties away from zero; `d > 0`. `q32` has no general divide-and-round.
fn round_div(n: i128, d: i128) -> Result<i128, HeldOutError> {
    if d <= 0 {
        return Err(HeldOutError::Shape("non-positive divisor".to_string()));
    }
    let (q, r) = (n / d, n % d);
    let mag = if r < 0 { -r } else { r };
    Ok(if 2 * mag >= d {
        if n < 0 {
            q - 1
        } else {
            q + 1
        }
    } else {
        q
    })
}

/// `sum / n` as one Q32.32 word: the one division an aggregate mean performs.
fn mean_word(sum: i128, n: u64) -> Result<i64, HeldOutError> {
    i64::try_from(round_div(sum, i128::from(n))?).map_err(|_| HeldOutError::Overflow)
}

/// One scored row: per-row losses in Q32.32, the top-1 agreement, and the next-token
/// log-probabilities when the row predicts a token.
#[derive(Debug, Clone, Copy, Default)]
struct RowScore {
    kl: i64,
    tv: i64,
    hit: bool,
    paired: bool,
    lp_t: i64,
    lp_s: i64,
}

/// The pool task of [`Acc::score_logits`]: the two `rows × vocab` logit blocks, the target tokens and
/// the lowest-row refusal cell.
struct RowTasks<'a> {
    zt: &'a [i64],
    zs: &'a [i64],
    vocab: usize,
    tokens: &'a [u32],
    first: &'a FirstErr<usize, HeldOutError>,
}

impl ChunkTask<RowScore> for RowTasks<'_> {
    fn run(&self, _c: usize, start: usize, piece: &mut [RowScore]) {
        if let Some(slot) = piece.first_mut() {
            match score_row(self.zt, self.zs, self.vocab, self.tokens, start) {
                Ok(s) => *slot = s,
                Err(e) => self.first.record(start, e),
            }
        }
    }
}

/// Score row `r` of a paired logit block: forward KL, total variation, top-1 agreement, and the two
/// next-token log-probabilities.
///
/// # Errors
/// `Head` from [`kl_row`], [`tv_row`] or [`log_softmax_row`], `Shape` for a short row or a next
/// token past the vocabulary, `Overflow` from a narrowing.
///
/// # Complexity
/// Time `O(vocab)`: two head passes, two `argmax` scans, at most two [`log_softmax_row`] calls;
/// space `O(vocab)` for the head's row outputs.
fn score_row(
    zt: &[i64],
    zs: &[i64],
    vocab: usize,
    tokens: &[u32],
    r: usize,
) -> Result<RowScore, HeldOutError> {
    let teacher_row = zt
        .get(r * vocab..(r + 1) * vocab)
        .ok_or_else(|| HeldOutError::Shape("teacher row past logits".to_string()))?;
    let student_row = zs
        .get(r * vocab..(r + 1) * vocab)
        .ok_or_else(|| HeldOutError::Shape("student row past logits".to_string()))?;
    let (kl, _) = kl_row(student_row, teacher_row).map_err(HeldOutError::Head)?;
    let (tv, _) = tv_row(student_row, teacher_row).map_err(HeldOutError::Head)?;
    let mut out = RowScore {
        kl,
        tv,
        hit: argmax(teacher_row) == argmax(student_row),
        ..RowScore::default()
    };
    if let Some(&next_tok) = tokens.get(r + 1) {
        let next = usize::try_from(next_tok).map_err(|_| HeldOutError::Overflow)?;
        for (row, slot) in [(teacher_row, &mut out.lp_t), (student_row, &mut out.lp_s)] {
            let lp = log_softmax_row(row).map_err(HeldOutError::Head)?;
            *slot = lp
                .get(next)
                .copied()
                .ok_or_else(|| HeldOutError::Shape("next token past vocabulary".to_string()))?;
        }
        out.paired = true;
    }
    Ok(out)
}

impl Acc {
    /// Accumulate paired logit rows: per-row forward KL and TV, top-1 agreement and next-token
    /// log-probabilities. `zt`/`zs` are `rows × vocab` row-major; `tokens` is indexed at `r + 1`, so
    /// a suffix caller passes the suffix's first token onward.
    ///
    /// # Errors
    /// `Shape` for a zero vocabulary, a length that is not `rows × vocab`, mismatched lengths or
    /// short metadata; `Head`/`Overflow` as [`HeldOutError`] states.
    ///
    /// # Complexity
    /// Unit cost `rows·vocab` word ops (five head passes over every entry) once per call, `≥ 10⁶` at
    /// any real vocabulary, so the rows are split across [`chunks_mut_global`] tasks; space
    /// `O(rows)` cells plus each task's `O(vocab)` head rows.
    fn score_logits(
        &mut self,
        zt: &[i64],
        zs: &[i64],
        vocab: usize,
        tokens: &[u32],
    ) -> Result<(), HeldOutError> {
        if vocab == 0 {
            return Err(HeldOutError::Shape("zero vocabulary".to_string()));
        }
        if !zt.len().is_multiple_of(vocab) || zs.len() != zt.len() {
            return Err(HeldOutError::Shape(format!(
                "logits {} / {} not a multiple of vocab {vocab}",
                zt.len(),
                zs.len()
            )));
        }
        let rows = zt.len() / vocab;
        if tokens.len() < rows {
            return Err(HeldOutError::Shape(format!(
                "{} tokens for {rows} scored rows",
                tokens.len()
            )));
        }
        let mut scored = vec![RowScore::default(); rows];
        let first: FirstErr<usize, HeldOutError> = FirstErr::new();
        chunks_mut_global(
            &mut scored,
            1,
            &RowTasks {
                zt,
                zs,
                vocab,
                tokens,
                first: &first,
            },
        );
        if let Some((_, e)) = first.take() {
            return Err(e);
        }
        // The ordered fold keeps the accumulation independent of the pool's schedule.
        for s in &scored {
            self.kl = add(self.kl, i128::from(s.kl))?;
            self.tv = add(self.tv, i128::from(s.tv))?;
            if s.hit {
                self.top1 += 1;
            }
            self.tokens += 1;
            if s.paired {
                self.nll_t = add(self.nll_t, i128::from(s.lp_t))?;
                self.nll_s = add(self.nll_s, i128::from(s.lp_s))?;
                self.pairs += 1;
            }
        }
        Ok(())
    }

    /// Score one sequence: the teacher's and the student's [`forward`], then the row accumulation.
    ///
    /// # Complexity
    /// Time `O(cost(forward_t) + cost(forward_s) + t·vocab)`; space `O(t·vocab)` plus the `Tape` a
    /// [`forward`] returns and this call drops.
    fn score(
        &mut self,
        teacher: &Weights,
        student: &Weights,
        cfg: &Config,
        tokens: &[u32],
    ) -> Result<(), HeldOutError> {
        let t = tokens.len();
        if t < 2 {
            return Err(HeldOutError::Shape(format!(
                "sequence length {t} < 2: no next-token position"
            )));
        }
        let v = cfg.vocab;
        if v == 0 {
            return Err(HeldOutError::Shape("zero vocabulary".to_string()));
        }
        let (lt, _tape_t) = forward(teacher, cfg, tokens).map_err(HeldOutError::Model)?;
        let (ls, _tape_s) = forward(student, cfg, tokens).map_err(HeldOutError::Model)?;
        if lt.len() != t * v || ls.len() != t * v {
            return Err(HeldOutError::Shape(format!(
                "logits {} × {} != t·vocab {}",
                lt.len(),
                ls.len(),
                t * v
            )));
        }
        self.score_logits(&lt, &ls, v, tokens)
    }

    /// Divide the exact accumulators into the fixed-point mean words: one rounding per mean. `Shape`
    /// when no next-token position was scored.
    fn finish(self) -> Result<HeldOut, HeldOutError> {
        if self.tokens == 0 || self.pairs == 0 {
            return Err(HeldOutError::Shape("no scored positions".to_string()));
        }
        let one = i128::from(ONE);
        Ok(HeldOut {
            tokens: self.tokens,
            kl: mean_word(self.kl, self.tokens)?,
            tv: mean_word(self.tv, self.tokens)?,
            top1: mean_word(i128::from(self.top1) * one, self.tokens)?,
            nll_student: mean_word(
                self.nll_s.checked_neg().ok_or(HeldOutError::Overflow)?,
                self.pairs,
            )?,
            nll_teacher: mean_word(
                self.nll_t.checked_neg().ok_or(HeldOutError::Overflow)?,
                self.pairs,
            )?,
        })
    }
}

/// The held-out quality of `student` against `teacher` over one token sequence.
///
/// # Errors
/// As [`HeldOutError`] lists them; cost as [`Acc::score`].
pub fn held_out_seq(
    teacher: &Weights,
    student: &Weights,
    cfg: &Config,
    tokens: &[u32],
) -> Result<HeldOut, HeldOutError> {
    let mut acc = Acc::default();
    acc.score(teacher, student, cfg, tokens)?;
    acc.finish()
}

/// The held-out quality over `sequences`, pooled as exact integers, so the means are token-weighted
/// by `T_i` (`T_i − 1` for the NLL).
///
/// The sequence loop is serial because each iteration dispatches [`forward`] on the engine pool.
///
/// # Errors
/// As [`HeldOutError`] lists them, plus `Shape` when `sequences` is empty.
pub fn held_out(
    teacher: &Weights,
    student: &Weights,
    cfg: &Config,
    sequences: &[&[u32]],
) -> Result<HeldOut, HeldOutError> {
    if sequences.is_empty() {
        return Err(HeldOutError::Shape("no sequences".to_string()));
    }
    let mut acc = Acc::default();
    for &seq in sequences {
        acc.score(teacher, student, cfg, seq)?;
    }
    acc.finish()
}

/// One scored base row: the per-row sums the chunk accumulates, all Q32.32.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct RowSums {
    /// `Σ_{lp > −16} exp(lp)·(lp − log p_student)`, one rounding.
    pub kl: i64,
    /// `−log p_student(next token)`.
    pub nll_student: i64,
    /// `−log p_base(next token)`.
    pub nll_base: i64,
    /// `1` when the student `argmax` equals the base row's.
    pub top1: u64,
}

/// Score one base row against the student's logits, in Q32.32.
///
/// `z` is the student logit row and `lp` the base row's `log p`, both `v` Q32.32 words; `target` is
/// the next token's index and `base_argmax` the base row's own `argmax`. The log-sum-exp is
/// `max z + ln(Σ exp(z − max))` with the [`FLUSH`] rule of [`crate::learn::grad::head`]; the KL is
/// the reference sum over entries with `log p > −16` (`perplexity.cpp:229–236`), top-1 the student
/// `argmax` against `base_argmax` (`:238–240`).
///
/// # Errors
/// [`HeldOutError::Shape`] for an empty row, mismatched lengths or a target past the vocabulary;
/// [`HeldOutError::Overflow`] when a shifted logit, the exponential sum, `lse`, a log-probability or
/// the rounded KL leaves its range.
///
/// # Complexity
/// Time `O(v)`: `v` [`fixed_exp`] calls, one [`fixed_ln`], one `v`-term KL pass. A row is one
/// vector pass (≤ `10⁵` word ops), so the row stays serial; the caller's row loop is the big pass.
pub fn score_base_row(
    z: &[i64],
    lp: &[i64],
    target: usize,
    base_argmax: Option<usize>,
) -> Result<RowSums, HeldOutError> {
    let v = z.len();
    if v == 0 || lp.len() != v {
        return Err(HeldOutError::Shape("base row width".to_string()));
    }
    if target >= v {
        return Err(HeldOutError::Shape("base target past vocab".to_string()));
    }
    let mut m = z[0];
    for &zk in z {
        if zk > m {
            m = zk;
        }
    }
    // Flat passes and flag forms: the fragment carries no `continue`, no `?` inside a nested block
    // and no `Iterator::max`; `base_term` holds the flush edge and the two refusals.
    let mut sum: i128 = 0;
    let mut err: Option<HeldOutError> = None;
    for &zk in z {
        if err.is_none() {
            let u = i128::from(zk) - i128::from(m);
            match base_term(u) {
                Ok(e) => match add(sum, i128::from(e)) {
                    Ok(a) => sum = a,
                    Err(x) => err = Some(x),
                },
                Err(x) => err = Some(x),
            }
        }
    }
    if let Some(x) = err {
        return Err(x);
    }
    let s = i64::try_from(sum).map_err(|_| HeldOutError::Overflow)?;
    let ln_s = fixed_ln(s).map_err(|_| HeldOutError::Overflow)?;
    let lse = m.checked_add(ln_s).ok_or(HeldOutError::Overflow)?;
    let nll_student = (i128::from(lse) - i128::from(z[target]))
        .try_into()
        .map_err(|_| HeldOutError::Overflow)?;
    let nll_base = 0i64.checked_sub(lp[target]).ok_or(HeldOutError::Overflow)?;
    let mut acc: i128 = 0;
    let mut failed = false;
    for i in 0..v {
        if !failed && i128::from(lp[i]) > FLUSH {
            let logp_s = i128::from(z[i]) - i128::from(lse);
            match fixed_exp(lp[i]) {
                Ok(p) => match add(acc, i128::from(p) * (i128::from(lp[i]) - logp_s)) {
                    Ok(a) => acc = a,
                    Err(_) => failed = true,
                },
                Err(_) => failed = true,
            }
        }
    }
    if failed {
        return Err(HeldOutError::Overflow);
    }
    // The two-`Option` comparison is written out: the model carries no `PartialEq` for `Option`.
    let hit = match argmax(z) {
        Some(i) => match base_argmax {
            Some(j) => i == j,
            None => false,
        },
        None => false,
    };
    Ok(RowSums {
        kl: round_q32_even(acc).map_err(|_| HeldOutError::Overflow)?,
        nll_student,
        nll_base,
        top1: u64::from(hit),
    })
}

/// `exp(z_i − m)` for one shifted Q32.32 logit, zero below the [`FLUSH`] edge. `O(1)`;
/// [`HeldOutError::Overflow`] when the shifted word leaves `i64` or [`fixed_exp`] refuses.
fn base_term(u: i128) -> Result<i64, HeldOutError> {
    if u < FLUSH {
        return Ok(0);
    }
    fixed_exp(i64::try_from(u).map_err(|_| HeldOutError::Overflow)?)
        .map_err(|_| HeldOutError::Overflow)
}

/// Score one chunk of a llama.cpp `--kl-divergence-base` file against the student engine.
///
/// The chunk's tokens are prefilled on the engine's [`KernelMode::Q8Act`] path; each scored position
/// — `n_ctx/2 .. n_ctx − 2`, the rows llama.cpp writes — takes its logits from
/// [`Engine::lm_head_fixed`] and is scored by [`score_base_row`] against the stored row at the same
/// index, whose target token is the chunk token one position later. The base `log p` values are
/// decoded to one Q32.32 word each here, the input boundary.
///
/// # Errors
/// [`HeldOutError::Shape`] for a chunk shorter than two tokens, a zero or mismatched vocabulary, no
/// scored position, or a row block that does not hold `n_ctx − 1 − n_ctx/2` rows;
/// [`HeldOutError::Engine`] for a decode-state, prefill or head refusal;
/// [`HeldOutError::Overflow`] when a base `log p` leaves the grid.
///
/// # Complexity
/// Time `O(cost(prefill) + rows·(cost(head) + n_vocab))`: one `Q8Act` prefill of `n_ctx` columns,
/// then `rows` heads of `O(vocab·n_embd)` multiply-adds and one `O(n_vocab)` scoring pass per row.
/// Space `O(n_ctx·n_embd)` for the states and KV cache, `O(vocab)` per head row, `O(1)` more.
pub fn held_out_kldbase_chunk(
    student: &Engine,
    chunk: &KldChunk,
) -> Result<BaseScore, HeldOutError> {
    let toks = chunk.tokens.as_slice();
    let n_ctx = toks.len();
    if n_ctx < 2 {
        return Err(HeldOutError::Shape(format!(
            "chunk length {n_ctx} < 2: no scored position"
        )));
    }
    let v = student.config.vocab_size;
    if v == 0 || v != chunk.n_vocab {
        return Err(HeldOutError::Shape(format!(
            "student vocab {v} != base {}",
            chunk.n_vocab
        )));
    }
    let first = n_ctx / 2;
    let rows = n_ctx - 1 - first;
    if chunk.rows != rows {
        return Err(HeldOutError::Shape(format!(
            "{} base rows for {rows} scored positions",
            chunk.rows
        )));
    }
    if rows == 0 {
        return Err(HeldOutError::Shape(
            "no scored position in the chunk".to_string(),
        ));
    }
    let mut st = student
        .state(n_ctx)
        .map_err(|e| HeldOutError::Engine(format!("state: {e}")))?;
    let states = student
        .prefill_cols(&mut st, toks, KernelMode::Q8Act)
        .map_err(|e| HeldOutError::Engine(format!("prefill: {e}")))?;
    if states.len() != n_ctx {
        return Err(HeldOutError::Shape(format!(
            "{} prefill states for {n_ctx} tokens",
            states.len()
        )));
    }
    let (mut kl, mut nll_s, mut nll_b, mut top1) = (0i128, 0i128, 0i128, 0u64);
    let mut lp = vec![0i64; v];
    for r in 0..rows {
        let x = states
            .get(first + r)
            .ok_or_else(|| HeldOutError::Shape(format!("state {r} past prefill")))?;
        let z = student
            .lm_head_fixed(x)
            .map_err(|e| HeldOutError::Engine(format!("head: {e:?}")))?;
        if z.len() != v {
            return Err(HeldOutError::Shape(format!(
                "logits {} != vocab {v}",
                z.len()
            )));
        }
        let target = usize::try_from(
            *toks
                .get(first + r + 1)
                .ok_or_else(|| HeldOutError::Shape(format!("target {r} past chunk")))?,
        )
        .map_err(|_| HeldOutError::Overflow)?;
        for (i, slot) in lp.iter_mut().enumerate() {
            let value = chunk
                .log_prob(r, i)
                .ok_or_else(|| HeldOutError::Shape(format!("base code {r}/{i} missing")))?;
            *slot = to_grid(value, GRID_BOUND).ok_or(HeldOutError::Overflow)?;
        }
        let s = score_base_row(&z, &lp, target, chunk.argmax(r))?;
        kl = add(kl, i128::from(s.kl))?;
        nll_s = add(nll_s, i128::from(s.nll_student))?;
        nll_b = add(nll_b, i128::from(s.nll_base))?;
        top1 += s.top1;
    }
    let n = u64::try_from(rows).map_err(|_| HeldOutError::Overflow)?;
    Ok(BaseScore {
        tokens: n,
        kl: mean_word(kl, n)?,
        top1: mean_word(i128::from(top1) * i128::from(ONE), n)?,
        nll_student: mean_word(nll_s.checked_neg().ok_or(HeldOutError::Overflow)?, n)?,
        nll_base: mean_word(nll_b.checked_neg().ok_or(HeldOutError::Overflow)?, n)?,
    })
}
