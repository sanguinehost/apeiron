//! Held-out quality of a Q32.32 student against a reference distribution: mean forward
//! `KL(reference ‖ student)`, mean total variation, top-1 argmax agreement, and mean next-token
//! negative log-likelihood of each model. Over every scored position the evaluator returns the mean
//! forward KL `Σ_x p_t(x)·(log p_t(x) − log p_s(x))` ([`kl_row`]), the total variation
//! `½Σ_x |p_t(x) − p_s(x)|` ([`tv_row`]), the top-1 agreement, and the next-token NLL
//! `−log p(token_{t+1} | position t)` ([`log_softmax_row`]); a sequence's last position predicts
//! nothing and is excluded from the NLL (`T − 1` positions).
//!
//! Two logit sources feed one evaluator ([`Acc::score_logits`]): the whole-model
//! [`crate::learn::grad::model::forward`] ([`held_out`], [`held_out_seq`]) and the engine's shipped
//! [`KernelMode::Q8Act`] prefill against a stored llama.cpp `--kl-divergence-base` distribution
//! ([`held_out_kldbase_chunk`], [`BaseScore`]).
//!
//! # Carrier and error
//!
//! Every computed value is Q32.32 `i64` (`ONE = 2^32`), the head's carrier. A per-row loss is the
//! head's exact-`i128`, once-rounded value; rows are summed in checked `i128` and divided by the
//! position count once, in fixed point, at [`Acc::finish`], so a mean is within half a grid quantum
//! `2⁻³³` of the exact rational. `KL(p_t ‖ p_s)` is asymmetric, so [`kl_row`]'s argument order is
//! semantic. The base-file path's `log p` (a `u16` code with a binary32 scale and minimum,
//! [`crate::learn::fold::stats::kldbase`]) is an **input format**, converted to one grid word per
//! entry at [`to_grid`] and scored in the same fixed point as the student.
//!
//! [`HeldOut`] and [`BaseScore`] carry those exact words: `kl`, `tv`, `nll_*` are nats per
//! position and `top1` is a fraction of `ONE`, each one `Q32.32` `i64`. A caller that prints a
//! decimal divides by `ONE` at its print line; no metric is rounded to a float here.
//!
//! [`HeldOutError`]: empty inputs, a sequence shorter than two tokens, a zero or mismatched
//! vocabulary, a short logits or row block, a `forward`/engine refusal and a checked `i128`
//! overflow. It never panics and takes no `unsafe`.
//!
//! Grade `tested` (`tests/learn_fold_heldout.rs`); no Lean refinement links this file, which is not
//! on the extracted fragment. The engine source is [`Engine::prefill_cols`] under
//! [`KernelMode::Q8Act`] plus [`Engine::lm_head_fixed`] per scored position — the engine's own
//! arithmetic, not a second forward. The reference is llama.cpp's own `--kl-divergence-base` file
//! (`tools/perplexity/perplexity.cpp:1695–1800`, read by
//! [`crate::learn::fold::stats::kldbase`]), subsumed rather than regenerated by a second engine in
//! this crate; `heldout_kldbase_qwen05b` is the measurement that checks it.
//!
//! # Trust boundary
//!
//! The thread pool ([`chunks_mut_global`]) is the boundary of the row split. The base file's
//! binary32 scale and minimum are the input format [`crate::learn::fold::stats::kldbase`] decodes,
//! not a computed value; [`HeldOut`] and [`BaseScore`] carry exact `Q32.32` words, and a caller's
//! decimal conversion is outside this file.

