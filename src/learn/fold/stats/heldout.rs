//! Held-out quality of a Q32.32 student against a reference distribution: mean forward
//! `KL(reference ‖ student)`, mean total variation, top-1 argmax agreement, and mean next-token
//! negative log-likelihood of each model. Over every scored position the evaluator returns the mean
//! forward KL `Σ_x p_t(x)·(log p_t(x) − log p_s(x))` ([`kl_row`]), the total variation
//! `½Σ_x |p_t(x) − p_s(x)|` ([`tv_row`]), the top-1 agreement, and the next-token NLL
//! `−log p(token_{t+1} | position t)` ([`log_softmax_row`]); a sequence's last position predicts
//! nothing and is excluded from the NLL(`T − 1` positions).
//!
//! Two logit sources feed one evaluator ([`Acc::score_logits`]): the whole-model
//! [`crate::learn::grad::model::forward`] ([`held_out`], [`held_out_seq`]) and the engine's shipped
//! [`KernelMode::Q8Act`] prefill against a stored llama.cpp `--kl-divergence-base` distribution
//! ([`held_out_kldbase_chunk`], [`BaseScore`]).
//!
//! Logits are Q32.32 `i64` (`ONE = 2^32`), the head's carrier: on the whole-model path every per-row
//! loss is the head's exact-`i128`, once-rounded value, summed in checked `i128` and converted to
//! `f64` once at the end. `KL(p_t ‖ p_s)` is asymmetric, so [`kl_row`]'s argument order is semantic.
//! The base-file path has no Q32.32 reference — llama.cpp stores `log p` as a `u16` code with an
//! `f32` scale and minimum — so it scores in `f64`.
//!
//! Refusals ([`HeldOutError`]): empty inputs, a sequence shorter than two tokens, a zero or
//! mismatched vocabulary, a short logits or row block, a `forward`/engine refusal and a checked
//! `i128` overflow. It never panics and takes no `unsafe`.
//!
//! Grade `tested` (`tests/learn_fold_heldout.rs`); no Lean refinement links this file, which is not
//! on the extracted fragment. The engine source is [`Engine::prefill_cols`] under
//! [`KernelMode::Q8Act`] plus [`Engine::lm_head_fixed`] per scored position — the engine's own
//! arithmetic, not a second forward. The reference is llama.cpp's own `--kl-divergence-base` file
//! (`tools/perplexity/perplexity.cpp:1695–1800`, read by
//! [`crate::learn::fold::stats::kldbase`]), subsumed rather than regenerated by a second engine in
//! this crate; `heldout_kldbase_qwen05b` is the measurement that checks it.

#![allow(
    clippy::cast_precision_loss,
    clippy::many_single_char_names,
    reason = "the i128/f64 boundary is the one deliberate conversion, made once per aggregate after \
              the exact integer sums; `t`/`v`/`r` are the schedule's position, vocabulary and row \
              indices"
)]

use crate::engine::{Engine, KernelMode, ONE};
use crate::learn::fold::stats::kldbase::KldChunk;
use crate::learn::grad::head::{kl_row, log_softmax_row, tv_row, HeadError};
use crate::learn::grad::model::{forward, Config, ModelError, Weights};

/// A refused held-out evaluation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum HeldOutError {
    /// A whole-model [`forward`] refused: an empty sequence, a token past the vocabulary, a shape
    /// disagreement or an overflow.
    Model(ModelError),
    /// A head row refused: a shape or overflow, or the unreachable `exp`/`ln` refusals.
    Head(HeadError),
    /// The evaluator's own shape check: an empty sequence list, a sequence shorter than two tokens,
    /// a zero vocabulary, a logits buffer that is not `t × vocab`, or token metadata that does not
    /// cover the scored rows.
    Shape(String),
    /// A checked `i128` accumulation left its range.
    Overflow,
    /// The engine source refused — a decode state, a prefill or a head row — or two engines disagree
    /// on geometry; the carried text is that error's own message, prefixed by the phase.
    Engine(String),
}

/// The per-chunk score against a stored base: llama.cpp's `--kl-divergence` protocol.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BaseScore {
    /// Scored positions, `n_ctx − 1 − n_ctx/2`.
    pub tokens: u64,
    /// Mean forward `KL(p_base ‖ p_student)` in nats per position, over base entries with
    /// `log p > −16` exactly as the reference sums it.
    pub kl: f64,
    /// Fraction of scored positions whose student `argmax` equals the base row's `argmax`.
    pub top1: f64,
    /// Mean `−log p_student(next token)` in nats over the scored positions.
    pub nll_student: f64,
    /// Mean `−log p_base(next token)` in nats over the scored positions: `log` of llama.cpp's base
    /// PPL column.
    pub nll_base: f64,
}

/// The scored held-out quality of a student against a teacher.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HeldOut {
    /// Scored positions `Σ_i T_i`: the denominator of `kl`, `tv` and `top1`.
    pub tokens: u64,
    /// Mean forward `KL(teacher ‖ student)` per position, in nats.
    pub kl: f64,
    /// Mean total variation `½Σ_x |p_teacher(x) − p_student(x)|` per position, in `[0, 1]`.
    pub tv: f64,
    /// Fraction of positions where the teacher and student `argmax` agree, in `[0, 1]`.
    pub top1: f64,
    /// Mean `−log p_student(next token)` in nats over the next-token positions (`T_i − 1` each).
    pub nll_student: f64,
    /// Mean `−log p_teacher(next token)` in nats, over the same positions as `nll_student`.
    pub nll_teacher: f64,
}

/// Exact Q32.32 accumulators over the scored positions; the division into the `f64` means happens
/// once, in [`Acc::finish`].
#[derive(Debug, Clone, Copy, Default)]
struct Acc {
    /// Scored positions, `Σ_i T_i`.
    tokens: u64,
    /// Next-token positions, `Σ_i (T_i − 1)`.
    pairs: u64,
    /// `Σ` of the per-row forward KL in Q32.32.
    kl: i128,
    /// `Σ` of the per-row total variation in Q32.32.
    tv: i128,
    /// Positions whose teacher and student `argmax` agree.
    top1: u64,
    /// `Σ` of the teacher `log p(next token)` in Q32.32 (negative).
    nll_t: i128,
    /// `Σ` of the student `log p(next token)` in Q32.32 (negative).
    nll_s: i128,
}

/// First index of the row maximum, ties to the lower index; `None` for an empty row.
fn argmax(row: &[i64]) -> Option<usize> {
    let mut best: Option<(usize, i64)> = None;
    for (i, &z) in row.iter().enumerate() {
        match best {
            Some((_, b)) if b >= z => {}
            _ => best = Some((i, z)),
        }
    }
    best.map(|(i, _)| i)
}

/// Checked `i128` addition.
fn add(a: i128, b: i128) -> Result<i128, HeldOutError> {
    a.checked_add(b).ok_or(HeldOutError::Overflow)
}

impl Acc {
    /// Accumulate paired logit rows: per-row forward KL and TV, top-1 agreement and next-token
    /// log-probabilities. `zt`/`zs` are `rows × vocab` Q32.32 row-major; `tokens` covers the rows and
    /// is indexed at `r + 1`, so a suffix caller passes the suffix's first token onward. `Shape` for a
    /// zero vocabulary, a length that is not `rows × vocab`, mismatched lengths or short metadata;
    /// `Head`/`Overflow` as [`HeldOutError`] states.
    ///
    /// Time `O(rows·vocab)`: one [`kl_row`], one [`tv_row`], two `argmax` scans and at most two
    /// [`log_softmax_row`] calls per row; space `O(1)`.
    fn score_logits(
        &mut self,
        zt: &[i64],
        zs: &[i64],
        vocab: usize,
        tokens: &[u32],
    ) -> Result<(), HeldOutError> {
        if vocab == 0 {
            return Err(HeldOutError::Shape("zero vocabulary".to_string()));
        }
        if !zt.len().is_multiple_of(vocab) || zs.len() != zt.len() {
            return Err(HeldOutError::Shape(format!(
                "logits {} / {} not a multiple of vocab {vocab}",
                zt.len(),
                zs.len()
            )));
        }
        let rows = zt.len() / vocab;
        if tokens.len() < rows {
            return Err(HeldOutError::Shape(format!(
                "{} tokens for {rows} scored rows",
                tokens.len()
            )));
        }
        for r in 0..rows {
            let teacher_row = zt
                .get(r * vocab..(r + 1) * vocab)
                .ok_or_else(|| HeldOutError::Shape("teacher row past logits".to_string()))?;
            let student_row = zs
                .get(r * vocab..(r + 1) * vocab)
                .ok_or_else(|| HeldOutError::Shape("student row past logits".to_string()))?;
            let (kl, _) = kl_row(student_row, teacher_row).map_err(HeldOutError::Head)?;
            let (tv, _) = tv_row(student_row, teacher_row).map_err(HeldOutError::Head)?;
            self.kl = add(self.kl, i128::from(kl))?;
            self.tv = add(self.tv, i128::from(tv))?;
            if argmax(teacher_row) == argmax(student_row) {
                self.top1 += 1;
            }
            self.tokens += 1;
            if let Some(&next_tok) = tokens.get(r + 1) {
                let next = usize::try_from(next_tok).map_err(|_| HeldOutError::Overflow)?;
                let row_logp = |z: &[i64]| -> Result<i64, HeldOutError> {
                    let lp = log_softmax_row(z).map_err(HeldOutError::Head)?;
                    lp.get(next).copied().ok_or_else(|| {
                        HeldOutError::Shape("next token past vocabulary".to_string())
                    })
                };
                let lp_t = row_logp(teacher_row)?;
                let lp_s = row_logp(student_row)?;
                self.nll_t = add(self.nll_t, i128::from(lp_t))?;
                self.nll_s = add(self.nll_s, i128::from(lp_s))?;
                self.pairs += 1;
            }
        }
        Ok(())
    }

    /// Score one sequence: the teacher's and the student's [`forward`], then the per-row
    /// accumulation. Time `O(cost(forward_t) + cost(forward_s) + t·vocab)`; space `O(t·vocab)` plus
    /// the `Tape` a [`forward`] returns and this call drops.
    fn score(
        &mut self,
        teacher: &Weights,
        student: &Weights,
        cfg: &Config,
        tokens: &[u32],
    ) -> Result<(), HeldOutError> {
        let t = tokens.len();
        if t < 2 {
            return Err(HeldOutError::Shape(format!(
                "sequence length {t} < 2: no next-token position"
            )));
        }
        let v = cfg.vocab;
        if v == 0 {
            return Err(HeldOutError::Shape("zero vocabulary".to_string()));
        }
        let (lt, _tape_t) = forward(teacher, cfg, tokens).map_err(HeldOutError::Model)?;
        let (ls, _tape_s) = forward(student, cfg, tokens).map_err(HeldOutError::Model)?;
        if lt.len() != t * v || ls.len() != t * v {
            return Err(HeldOutError::Shape(format!(
                "logits {} × {} != t·vocab {}",
                lt.len(),
                ls.len(),
                t * v
            )));
        }
        self.score_logits(&lt, &ls, v, tokens)
    }

    /// Divide the exact accumulators into the `f64` means, the one point of conversion. `Shape` when
    /// no next-token position was scored.
    fn finish(self) -> Result<HeldOut, HeldOutError> {
        if self.tokens == 0 || self.pairs == 0 {
            return Err(HeldOutError::Shape("no scored positions".to_string()));
        }
        let one = ONE as f64;
        let n = self.tokens as f64;
        let m = self.pairs as f64;
        Ok(HeldOut {
            tokens: self.tokens,
            kl: self.kl as f64 / one / n,
            tv: self.tv as f64 / one / n,
            top1: self.top1 as f64 / n,
            nll_student: -(self.nll_s as f64) / one / m,
            nll_teacher: -(self.nll_t as f64) / one / m,
        })
    }
}

/// The held-out quality of `student` against `teacher` over one token sequence; errors and cost as
/// [`Acc::score`] and [`HeldOutError`], with `Shape` also for a short sequence or a zero vocabulary.
///
/// # Errors
///
/// As [`HeldOutError`] lists them.
pub fn held_out_seq(
    teacher: &Weights,
    student: &Weights,
    cfg: &Config,
    tokens: &[u32],
) -> Result<HeldOut, HeldOutError> {
    let mut acc = Acc::default();
    acc.score(teacher, student, cfg, tokens)?;
    acc.finish()
}

/// The held-out quality over `sequences`, each on its own causal [`forward`] and pooled as exact
/// integers, so the means are token-weighted by `T_i` (`T_i − 1` for the NLL). `Shape` when
/// `sequences` is empty, plus every refusal of [`held_out_seq`]; cost is their sum.
///
/// # Errors
///
/// As [`HeldOutError`] lists them, plus `Shape` when `sequences` is empty.
pub fn held_out(
    teacher: &Weights,
    student: &Weights,
    cfg: &Config,
    sequences: &[&[u32]],
) -> Result<HeldOut, HeldOutError> {
    if sequences.is_empty() {
        return Err(HeldOutError::Shape("no sequences".to_string()));
    }
    let mut acc = Acc::default();
    for &seq in sequences {
        acc.score(teacher, student, cfg, seq)?;
    }
    acc.finish()
}

/// Score one chunk of a llama.cpp `--kl-divergence-base` file against the student engine.
///
/// The chunk's own tokens are prefilled on the engine's [`KernelMode::Q8Act`] path
/// ([`Engine::prefill_cols`]); each scored position — `n_ctx/2 .. n_ctx − 2`, the rows llama.cpp
/// writes — takes its logits from [`Engine::lm_head_fixed`] and is scored against the stored row at
/// the same index, whose target token is the chunk token one position later. The KL is the reference
/// sum `Σ p_base·(log p_base − log p_student)` over entries with `log p_base > −16`
/// (`perplexity.cpp:229–236`), top-1 the student `argmax` against the base row's (`:238–240`), and
/// the NLL `−log p(next token)` for each side.
///
/// # Errors
///
/// [`HeldOutError::Shape`] for a chunk shorter than two tokens, a zero or mismatched vocabulary, or a
/// row block that does not hold `n_ctx − 1 − n_ctx/2` rows; [`HeldOutError::Engine`] for a
/// decode-state, prefill or head refusal.
///
/// # Complexity
///
/// Time `O(cost(prefill) + rows·(cost(head) + n_vocab))`: one `Q8Act` prefill of `n_ctx` columns,
/// each `O(n_layer·(n_embd² + n_embd·n_ff) + pos·n_head·head_dim)`, then `rows` heads of
/// `O(vocab·n_embd)` multiply-adds and one `O(n_vocab)` scoring pass per row. Space
/// `O(n_ctx·n_embd)` for the prefill states and KV cache, `O(vocab)` per head row, `O(1)` more.
pub fn held_out_kldbase_chunk(
    student: &Engine,
    chunk: &KldChunk,
) -> Result<BaseScore, HeldOutError> {
    let toks = chunk.tokens.as_slice();
    let n_ctx = toks.len();
    if n_ctx < 2 {
        return Err(HeldOutError::Shape(format!(
            "chunk length {n_ctx} < 2: no scored position"
        )));
    }
    let v = student.config.vocab_size;
    if v == 0 || v != chunk.n_vocab {
        return Err(HeldOutError::Shape(format!(
            "student vocab {v} != base {}",
            chunk.n_vocab
        )));
    }
    let first = n_ctx / 2;
    let rows = n_ctx - 1 - first;
    if chunk.rows != rows {
        return Err(HeldOutError::Shape(format!(
            "{} base rows for {rows} scored positions",
            chunk.rows
        )));
    }
    let mut st = student
        .state(n_ctx)
        .map_err(|e| HeldOutError::Engine(format!("state: {e}")))?;
    let states = student
        .prefill_cols(&mut st, toks, KernelMode::Q8Act)
        .map_err(|e| HeldOutError::Engine(format!("prefill: {e}")))?;
    if states.len() != n_ctx {
        return Err(HeldOutError::Shape(format!(
            "{} prefill states for {n_ctx} tokens",
            states.len()
        )));
    }
    let inv = 1.0 / ONE as f64;
    let (mut kl, mut nll_s, mut nll_b, mut top1) = (0.0f64, 0.0f64, 0.0f64, 0u64);
    for r in 0..rows {
        let x = states
            .get(first + r)
            .ok_or_else(|| HeldOutError::Shape(format!("state {r} past prefill")))?;
        let z = student
            .lm_head_fixed(x)
            .map_err(|e| HeldOutError::Engine(format!("head: {e:?}")))?;
        if z.len() != v {
            return Err(HeldOutError::Shape(format!(
                "logits {} != vocab {v}",
                z.len()
            )));
        }
        let target = usize::try_from(
            *toks
                .get(first + r + 1)
                .ok_or_else(|| HeldOutError::Shape(format!("target {r} past chunk")))?,
        )
        .map_err(|_| HeldOutError::Overflow)?;
        let m = z
            .iter()
            .map(|&q| q as f64)
            .fold(f64::NEG_INFINITY, f64::max);
        let sum: f64 = z.iter().map(|&q| ((q as f64 - m) * inv).exp()).sum();
        let lse = m * inv + sum.ln();
        for (i, &q) in z.iter().enumerate() {
            let lp = chunk
                .log_prob(r, i)
                .ok_or_else(|| HeldOutError::Shape(format!("base code {r}/{i} missing")))?;
            if lp > -16.0 {
                kl += lp.exp() * (lp - (q as f64).mul_add(inv, -lse));
            }
        }
        let lp_t = chunk
            .log_prob(r, target)
            .ok_or_else(|| HeldOutError::Shape(format!("base code {r}/{target} missing")))?;
        let zs_t = ((*z.get(target).ok_or(HeldOutError::Overflow)?) as f64).mul_add(inv, -lse);
        nll_s -= zs_t;
        nll_b -= lp_t;
        if argmax(&z) == chunk.argmax(r) {
            top1 += 1;
        }
    }
    let n = rows as f64;
    Ok(BaseScore {
        tokens: rows as u64,
        kl: kl / n,
        top1: top1 as f64 / n,
        nll_student: nll_s / n,
        nll_base: nll_b / n,
    })
}
